import type { AixWire_Particles } from '~/modules/aix/server/api/aix.wiretypes';


export type ParticleServerLogLevel = false | 'srv-log' | 'srv-warn';

export type ParticleCGDialectEndReason = Extract<AixWire_Particles.CGEndReason, 'done-dialect' | 'issue-dialect'>;

/**
 * An issue as the parser states it; the transmitter completes the record (aix.issues.ts: bounds, the effect after the verdict).
 * `text` is the vendor's top-level message, else our sentence: plain, no markup, no service name; left out, the code's
 * sentence (for `model-filter`, the stop reason's). `detail` is any further vendor text. `causeCode` is the most specific
 * vendor code in scope; a numeric in-band code goes here as a string when the vendor gave no string code.
 * No HTTP status: the stream was a 200, an in-band code is not one.
 */
export type ParticleDialectIssue = { text?: string; detail?: string; causeCode?: string; retryAfterMs?: number } & (
  | { code?: 'service-error' | 'model-filter' | 'dispatch-parse'; effect?: 'failed' | 'notice' }  // default 'service-error', 'failed'. 'dispatch-parse': our processing of the service's data failed
  | { code: 'dispatch-cutoff'; effect: 'notice' }                                                  // onReadEnd only: the read closed before the final event this dialect always sends, after a failure it had stated
  | { code: 'service-tool'; effect?: 'lost' });                                                    // a hosted tool or operation failed; the generation goes on

/** What a parser may send as a control particle: the end and the issues have their own calls */
export type ParticleCGControlOp = Exclude<AixWire_Particles.ChatControlOp, { cg: 'end' } | { cg: 'aix-issue' } | { cg: 'issue' }>;

/** Rule: parsers translate each vendor unit 1:1, presentation is a render concern - kb/modules/AIX-ingestion.md lists where this does not hold yet */
export interface IParticleTransmitter {

  // Parser-initiated Control //

  /** Stop reading: the dialect ended. An issue that ends the read is two calls, in this order: addDialectIssue(...), then setDialectEnded('issue-dialect') */
  setDialectEnded(reason: ParticleCGDialectEndReason): void;

  /**
   * State an issue: sent at once as an `aix-issue` particle, at its place in the stream. The read goes on, whatever the
   * effect: what arrives after an error is worth reading (usage, a finish). It closes the open part: state it between
   * items, never inside one (a tool call's arguments).
   */
  addDialectIssue(issue: ParticleDialectIssue, serverLog?: ParticleServerLogLevel): void;

  /**
   * The model's finish, as data. Call it after the response content: after a clean or truncated stop reason an issue is a
   * notice. A filter stop the parser has words for: set the reason, then addDialectIssue({ code: 'model-filter', ... });
   * with no words, the reason alone is enough. Once an issue failed the generation, a reason that is not an error is ignored.
   */
  setTokenStopReason(reason: AixWire_Particles.GCTokenStopReason): void;


  // Parts data //

  /** Closes the current part, also flushing it out */
  endMessagePart(): void;

  /** Appends text, creating a part if missing [throttled] */
  appendText(textChunk: string): void;

  /** Appends reasoning text, creating a part if missing [throttled] */
  appendReasoningText(textChunk: string, options?: { weak?: 'tag', restart?: boolean }): void;

  /** Sets a reasoning signature, associated with the current reasoning text */
  setReasoningSignature(signature: string): void;

  /** Adds a raw (redacted) reasoning data parcel */
  addReasoningRedactedData(data: string): void;

  /** Appends test, with automatic heuristics for Particle splitting [throttled] */
  appendAutoText_weak(textChunk: string): void;

  /** Appends an audio file generated by the model */
  appendAudioInline(mimeType: string, base64Data: string, label: string, generator: string, durationMs: number): void;

  /** Appends an image generated by the model */
  appendImageInline(mimeType: string, base64Data: string, label: string, generator: string, prompt: string, hintSkipResize?: boolean): void;

  /** Appends a video generated by the model (EXPERIMENTAL: Gemini Omni; played in-memory, not persisted) */
  appendVideoInline(mimeType: string, base64Data: string, label: string, generator: string): void;

  /** Appends a hosted resource (e.g. Anthropic container file) - inline content between text fragments */
  appendHostedResource(hres: Extract<AixWire_Particles.PartParticleOp, { p: 'hres' }>): void;

  /** Appends a void notice - inline, display-only, dismissible, never sent upstream (e.g. replayed thinking dropped, file export discarded) */
  appendVoidNotice(vnt: Extract<AixWire_Particles.PartParticleOp, { p: 'vnt' }>): void;

  /**
   * Creates a FC part, flushing the previous one if needed, and starts adding data to it
   * @param id if null [Gemini], a new id will be generated to keep it linked to future tool responses
   * @param functionName required.
   * @param expectedArgsFmt 'incr_str' | 'json_object' - 'incr_str' for incremental string, 'json_object' for JSON object
   * @param args must be undefined, or match the expected Args Format
   */
  startFunctionCallInvocation(id: string | null, functionName: string, expectedArgsFmt: 'incr_str' | 'json_object', args: string | object | null): void;

  /** Appends data to a FC part [throttled] */
  appendFunctionCallInvocationArgs(id: string | null, argsJsonChunk: string): void;

  /** Creates a CE request part, flushing the previous one if needed, and completes it */
  addCodeExecutionInvocation(id: string | null, language: string, code: string, author: 'gemini_auto_inline' | 'code_interpreter'): void;

  /** Creates a CE result part, flushing the previous one if needed, and completes it */
  addCodeExecutionResponse(id: string | null, error: boolean | string, result: string, executor: 'gemini_auto_inline' | 'code_interpreter', environment: 'upstream'): void;

  /** Adds a URL citation part */
  appendUrlCitation(title: string, url: string, citationNumber?: number, startIndex?: number, endIndex?: number, textSnippet?: string, pubTs?: number): void;


  // Special //

  /** Sends control particles right away, such as aix-info/aix-retry-reset/... control particles */
  sendCGControl(cgCOp: ParticleCGControlOp, flushQueue?: boolean): void;

  /** Sends a void placeholder particle - temporary status with operation tracking */
  sendOperationState(
    mot: 'search-web' | 'gen-image' | 'code-exec', text: string,
    opts: { opId: string, state?: 'done' | 'error', parentOpId?: string, iTexts?: string[], oTexts?: string[] }
  ): void;

  /**
   * Sends vendor-specific state modifier for the last emitted part.
   * Used to attach opaque protocol state (e.g., Gemini thoughtSignature, Anthropic container) without polluting core part schemas.
   */
  sendSetVendorState(svs: Extract<AixWire_Particles.PartParticleOp, { p: 'svs' }>): void;

  // Non-parts data //

  /** Communicates the model name to the client */
  setModelName(modelName: string): void;

  /** Communicates the provider name to the client (e.g., OpenRouter provider routing) */
  setProviderInfraLabel(label: string): void;

  /** Communicates the upstream response handle, for remote control/resumability */
  setUpstreamHandle(handle: string, type: 'vnd.oai.responses' | 'vnd.gem.interactions'): void;

  /** Update the metrics, sent twice (after the first call, and then at the end of the transmission) */
  updateMetrics(update: Partial<AixWire_Particles.CGSelectMetrics>): void;

}
